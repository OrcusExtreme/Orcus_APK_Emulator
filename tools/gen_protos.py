"""Vendor the emulator's gRPC .proto files and generate Python stubs (ARCHITECTURE.md §11.7).

1. Read the protos from the installed emulator (default D:\\OrcusAPK\\sdk\\emulator\\lib) and check
   that its build matches the pin and that every file carries the Apache-2.0 header.
2. Copy them to src/orcus/emugrpc/protos/<build>/ (with a NOTICE).
3. Generate *_pb2.py / *_pb2_grpc.py / *.pyi into src/orcus/emugrpc/generated/ with grpcio-tools,
   rewrite their imports to package-relative ones, and write MANIFEST.json (sha256 of every file)
   for `--selftest`.

Run inside the dev venv: py tools/dev.py genprotos [sdk_emulator_dir]
"""

import hashlib
import importlib
import importlib.resources
import json
import re
import shutil
import sys
from pathlib import Path

sys.dont_write_bytecode = True
import devenv  # noqa: E402

sys.path.insert(0, str(devenv.REPO / "src"))
from orcus.common import pins  # noqa: E402

PROTOS = ("emulator_controller.proto", "snapshot_service.proto", "snapshot.proto")
PKG = devenv.REPO / "src" / "orcus" / "emugrpc"
PROTO_DIR = PKG / "protos" / pins.PROTO_DIR_NAME
GEN_DIR = PKG / "generated"
NOTICE = f"""These files are copied unchanged from Android Emulator {pins.EMULATOR.revision} (build {pins.EMULATOR_BUILD}),
emulator/lib/*.proto, downloaded from dl.google.com after the user accepted the Android SDK License.
Each file carries its original header: Copyright The Android Open Source Project,
licensed under the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0).
"""


def check_header(path: Path) -> None:
    head = " ".join(path.read_text(encoding="utf-8").splitlines()[:20]).replace("= ;", ",")
    if "Apache License" not in head or "Version 2.0" not in head:
        sys.exit(f"{path.name}: no Apache-2.0 header in the first 20 lines; not vendoring it")


def sha256(path: Path) -> str:
    """Line-ending neutral: git may check these text files out with CRLF."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"D:\OrcusAPK\sdk\emulator\lib")
    props = (src.parent / "source.properties").read_text(encoding="utf-8")
    if f"Pkg.BuildId={pins.EMULATOR_BUILD}" not in props:
        sys.exit(f"{src.parent} is not emulator build {pins.EMULATOR_BUILD}")

    if PROTO_DIR.parent.exists():
        shutil.rmtree(PROTO_DIR.parent)
    PROTO_DIR.mkdir(parents=True)
    for name in PROTOS:
        check_header(src / name)
        shutil.copyfile(src / name, PROTO_DIR / name)
    (PROTO_DIR / "NOTICE").write_text(NOTICE, encoding="utf-8", newline="\n")

    from grpc_tools import protoc   # dev-only dependency

    if GEN_DIR.exists():
        shutil.rmtree(GEN_DIR)
    GEN_DIR.mkdir()
    well_known = str(importlib.resources.files("grpc_tools") / "_proto")
    args = ["protoc", f"-I{PROTO_DIR}", f"-I{well_known}", f"--python_out={GEN_DIR}",
            f"--grpc_python_out={GEN_DIR}", f"--pyi_out={GEN_DIR}", *(str(PROTO_DIR / p) for p in PROTOS)]
    if protoc.main(args) != 0:
        sys.exit("protoc failed")

    local = {Path(p).stem + "_pb2" for p in PROTOS}
    pattern = re.compile(r"^import (\w+_pb2) as (\w+)$", re.MULTILINE)
    for f in sorted(GEN_DIR.glob("*.py*")):
        text = f.read_text(encoding="utf-8")
        text = pattern.sub(lambda m: f"from . import {m.group(1)} as {m.group(2)}" if m.group(1) in local else m.group(0),
                           text)
        text = re.sub(r"^import (\w+_pb2)$", lambda m: f"from . import {m.group(1)}" if m.group(1) in local
                      else m.group(0), text, flags=re.MULTILINE)
        f.write_text(text, encoding="utf-8", newline="\n")
    (GEN_DIR / "__init__.py").write_text(
        '"""Generated by tools/gen_protos.py from protos/' + pins.PROTO_DIR_NAME + '. Do not edit."""\n',
        encoding="utf-8", newline="\n")

    descriptors: dict[str, str] = {}
    for proto in PROTOS:   # what the packaged build can still check: the descriptors embedded in the stubs
        module = importlib.import_module(f"orcus.emugrpc.generated.{Path(proto).stem}_pb2")
        descriptors[module.__name__.rsplit(".", 1)[1]] = hashlib.sha256(module.DESCRIPTOR.serialized_pb).hexdigest()
    manifest = {
        "emulator_build": pins.EMULATOR_BUILD,
        "protos": {p.name: sha256(p) for p in sorted(PROTO_DIR.glob("*.proto"))},
        "generated": {g.name: sha256(g) for g in sorted(GEN_DIR.glob("*.py*")) if g.name != "MANIFEST.json"},
        "descriptors": descriptors,
    }
    (GEN_DIR / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    gencode = re.search(r"ValidateProtobufRuntimeVersion\(\s*_runtime_version\.Domain\.PUBLIC,\s*(\d+),\s*(\d+),\s*(\d+)",
                        (GEN_DIR / "emulator_controller_pb2.py").read_text(encoding="utf-8"))
    print(f"vendored {len(PROTOS)} protos into {PROTO_DIR}")
    print(f"generated {len(manifest['generated'])} files into {GEN_DIR}")
    if gencode:
        print("protobuf gencode version:", ".".join(gencode.groups()))


if __name__ == "__main__":
    main()
