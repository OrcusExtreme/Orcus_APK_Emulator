"""Regenerate requirements.lock and requirements-dev.lock with sha256 hashes.

The project only targets CPython 3.14 on Windows x64, so each pin carries the hash of the one
wheel pip picks for this platform. pip resolves with --dry-run --report (no installs); the dev
set is resolved with the runtime pins as constraints so both files agree.

Usage: py -3.14 tools/lock.py
"""

import json
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no tools/__pycache__ in the Drive folder
import devenv  # noqa: E402

HEADER = "# Generated by tools/lock.py for CPython 3.14 / win_amd64. Do not edit by hand.\n"


def resolve(python: Path, requirements: Path, report: Path, constraints: Path | None = None) -> list[tuple[str, str, str]]:
    argv = [str(python), "-m", "pip", "install", "--dry-run", "--ignore-installed", "--only-binary=:all:",
            "--quiet", "--report", str(report), "-r", str(requirements)]
    if constraints is not None:
        argv += ["-c", str(constraints)]
    subprocess.run(argv, env=devenv.dev_env(), check=True)
    data = json.loads(report.read_text(encoding="utf-8"))
    pins: list[tuple[str, str, str]] = []
    for item in data["install"]:
        name = item["metadata"]["name"]
        version = item["metadata"]["version"]
        archive = item["download_info"].get("archive_info", {})
        sha256 = archive.get("hashes", {}).get("sha256") or archive.get("hash", "").removeprefix("sha256=")
        if not sha256:
            sys.exit(f"no sha256 for {name} {version}")
        pins.append((name, version, sha256))
    return sorted(pins, key=lambda p: p[0].lower())


def render(pins: list[tuple[str, str, str]], include: str | None = None) -> str:
    lines = [HEADER]
    if include:
        lines.append(f"-r {include}\n")
    for name, version, sha256 in pins:
        lines.append(f"{name}=={version} \\\n    --hash=sha256:{sha256}\n")
    return "".join(lines)


def main() -> None:
    devenv.ensure_dirs()
    python = devenv.VENV_PY if devenv.VENV_PY.exists() else devenv.BASE_PY
    tmp = devenv.TMP
    runtime = resolve(python, devenv.REPO / "requirements.in", tmp / "lock-runtime.json")
    (devenv.REPO / "requirements.lock").write_text(render(runtime), encoding="utf-8", newline="\n")

    constraints = tmp / "lock-constraints.txt"
    constraints.write_text("".join(f"{n}=={v}\n" for n, v, _ in runtime), encoding="utf-8")
    dev = resolve(python, devenv.REPO / "requirements-dev.in", tmp / "lock-dev.json", constraints)
    runtime_names = {n.lower() for n, _, _ in runtime}
    dev_only = [p for p in dev if p[0].lower() not in runtime_names]
    (devenv.REPO / "requirements-dev.lock").write_text(render(dev_only, include="requirements.lock"),
                                                       encoding="utf-8", newline="\n")
    print(f"runtime: {len(runtime)} pins, dev-only: {len(dev_only)} pins")


if __name__ == "__main__":
    main()
