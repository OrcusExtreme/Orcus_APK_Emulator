"""Packaging (acceptance A8): trimming, licenses, the installer.

1. Copy the sources out of the Drive folder (Drive briefly locks freshly written files).
2. PyInstaller onedir with two executables sharing one folder: OrcusAPK.exe (windowed) and orcus-cli.exe, both with
   a version resource. Qt files the program never loads are left out (software OpenGL, extra platform and
   image plugins, TLS backends with the OpenSSL they pull in, every Qt translation but qtbase_ko), Qt stays in
   separate replaceable DLLs (LGPL), and NOTICE plus licenses\\ sit next to the EXEs.
3. Run the packaged checks: orcus-cli.exe selftest, OrcusAPK.exe --selftest, and with --boot-check also
   OrcusAPK.exe --boot-check (host and host_hidden cold boots).
4. With --gui-check: start the packaged window, wait for READY, kill it, and check no SDK process is left.
5. With --installer: the per-user Inno Setup installer (packaging\\orcus.iss) from the app folder, compiled by
   ISCC (Inno Setup 6, found in the usual places or through ORCUS_ISCC).

Usage: py tools/dev.py build [--boot-check] [--gui-check] [--installer | --installer-only] [--release]
       --release also copies the installer into the repository's release/ folder (the one shipped copy).
"""

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.dont_write_bytecode = True
import devenv  # noqa: E402

sys.path.insert(0, str(devenv.REPO / "src"))
from orcus.common import winjob  # noqa: E402

ORCUS_ROOT = Path(r"D:\OrcusAPK")
SRC_COPY = devenv.DEV_ROOT / "src-copy"
WORK = devenv.DEV_ROOT / "build"
DIST = devenv.DEV_ROOT / "dist"
APP = DIST / "OrcusAPK"
RELEASE = devenv.REPO / "release"
RUNTIME_DISTS = ("PySide6_Essentials", "shiboken6", "grpcio", "protobuf", "apkInspector", "typing_extensions")
# license texts next to the EXEs: each runtime package's own, Python's (with OpenSSL, libffi, bzip2 ...),
# the PyInstaller bootloader's, and the LGPL/GPL 3.0 for Qt (its wheel carries no license text)
LICENSE_DISTS = (*RUNTIME_DISTS, "pyinstaller")
ISCC_PLACES = (Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
               Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Inno Setup 6" / "ISCC.exe",
               Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Inno Setup 6" / "ISCC.exe")

SPEC = """# Generated by tools/build.py
from PyInstaller.utils.hooks import copy_metadata

src = {src!r}
datas = [({lock!r}, "."), ({manifest!r}, "orcus/emugrpc/generated"), ({icon!r}, "orcus/resources")]
for dist in {dists!r}:
    datas += copy_metadata(dist)
excludes = ["tkinter", "PySide6.QtQml", "PySide6.QtQuick", "PySide6.QtOpenGL", "PySide6.QtSvg",
            "grpc_tools"]   # grpc._runtime_protos asks for grpc_tools; Orcus never compiles protos at run time
# --selftest imports these by name (the GUI imports them for real too; QtNetwork = single-instance hand-over)
hiddenimports = ["PySide6.QtCore", "PySide6.QtGui", "PySide6.QtWidgets", "PySide6.QtNetwork", "apkInspector",
                 "orcus.gui.app"]
# never loaded: software OpenGL (the window draws with the raster engine), other platform plugins, image
# formats nobody opens (PNG and BMP are built in; ico, jpeg, gif, webp stay), SVG, touch input, network
# information, the TLS backends and the OpenSSL 3 DLLs found for them (single-instance pipes need no TLS)
DROP = {drop!r}


def keep(entry):
    dest = entry[0].replace("\\\\", "/").lower()
    name = dest.rsplit("/", 1)[-1]
    if name in DROP:
        return False
    if "/translations/" in "/" + dest:
        return name == "qtbase_ko.qm"   # Qt's own Yes/No/OK/Cancel in Korean (gui.app)
    return True


def trim(toc):
    return [e for e in toc if keep(e)]


def analysis(script):
    return Analysis([script], pathex=[src], datas=datas, hiddenimports=hiddenimports, excludes=excludes,
                    noarchive=False)


gui = analysis(src + "/orcus/__main__.py")
cli = analysis(src + "/orcus/cli.py")
gui_exe = EXE(PYZ(gui.pure), gui.scripts, [], exclude_binaries=True, name="OrcusAPK", console=False,
              upx=False, icon={icon!r}, version={gui_version!r})
cli_exe = EXE(PYZ(cli.pure), cli.scripts, [], exclude_binaries=True, name="orcus-cli", console=True, upx=False,
              icon={icon!r}, version={cli_version!r})
COLLECT(gui_exe, trim(gui.binaries), trim(gui.datas), cli_exe, trim(cli.binaries), trim(cli.datas),
        name="OrcusAPK", upx=False)
"""

DROP = ("opengl32sw.dll", "qt6svg.dll", "qdirect2d.dll", "qminimal.dll", "qoffscreen.dll", "qtiff.dll", "qicns.dll",
        "qtga.dll", "qwbmp.dll", "qsvg.dll", "qsvgicon.dll", "qtuiotouchplugin.dll", "qnetworklistmanager.dll",
        "qopensslbackend.dll", "qschannelbackend.dll", "qcertonlybackend.dll", "libcrypto-3-x64.dll",
        "libssl-3-x64.dll")

VERSION_FILE = """VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
                    subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'OrcusExtreme'),
      StringStruct('FileDescription', {description!r}),
      StringStruct('FileVersion', {version!r}),
      StringStruct('InternalName', {name!r}),
      StringStruct('OriginalFilename', {exe!r}),
      StringStruct('ProductName', 'Orcus APK Emulator'),
      StringStruct('ProductVersion', {version!r})])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def app_version() -> str:
    text = (devenv.REPO / "src" / "orcus" / "__init__.py").read_text(encoding="utf-8")
    m = re.search(r'__version__\s*=\s*"([^"]+)"', text)
    if m is None:
        raise SystemExit("no __version__ in src/orcus/__init__.py")
    return m.group(1)


def numeric(version: str) -> tuple[int, int, int, int]:
    """0.2.0.dev0 -> (0, 2, 0, 0): Windows version resources take four numbers."""
    nums = [int(n) for n in re.findall(r"\d+", version.split(".dev")[0].split("rc")[0])][:4]
    return tuple((nums + [0, 0, 0, 0])[:4])   # type: ignore[return-value]


def version_file(name: str, description: str, version: str) -> Path:
    path = WORK / f"version-{name}.txt"
    path.write_text(VERSION_FILE.format(nums=numeric(version), description=description, version=version, name=name,
                                        exe=f"{name}.exe"), encoding="utf-8")
    return path


def copy_sources() -> Path:
    devenv.remove_tree(SRC_COPY)
    shutil.copytree(devenv.REPO / "src", SRC_COPY / "src", ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    for name in ("requirements.lock", "NOTICE", "pyproject.toml"):
        shutil.copy2(devenv.REPO / name, SRC_COPY / name)
    return SRC_COPY / "src"


def add_licenses() -> list[str]:
    """NOTICE and licenses\\ next to the EXEs (the installer copies the whole folder)."""
    shutil.copy2(devenv.REPO / "NOTICE", APP / "NOTICE.txt")
    out = APP / "licenses"
    out.mkdir(exist_ok=True)
    for src in sorted((devenv.REPO / "packaging" / "licenses").glob("*.txt")):
        shutil.copy2(src, out / src.name)
    shutil.copy2(devenv.BASE_PY.parent / "LICENSE.txt", out / "Python-LICENSE.txt")
    wanted = {d.lower().replace("-", "_") for d in LICENSE_DISTS}
    for info in devenv.SITE_PACKAGES.glob("*.dist-info"):
        dist = info.name.split("-")[0].lower()
        if dist not in wanted:
            continue
        for f in info.rglob("*"):
            if f.is_file() and re.match(r"(LICEN[CS]E|COPYING|NOTICE)", f.name, re.IGNORECASE):
                shutil.copy2(f, out / f"{info.name.split('-')[0]}-{f.name}")
    return sorted(p.name for p in out.iterdir())


def folder_mb(path: Path) -> float:
    return round(sum(f.stat().st_size for f in path.rglob("*") if f.is_file()) / 1e6, 1)


def newest(pattern: str, since: float) -> Path | None:
    logs = ORCUS_ROOT / "logs"
    files = [p for p in logs.glob(pattern) if p.stat().st_mtime >= since]
    return max(files, key=lambda p: p.stat().st_mtime) if files else None


def find_iscc() -> Path | None:
    named = os.environ.get("ORCUS_ISCC")
    for place in ((Path(named),) if named else ()) + ISCC_PLACES:
        if place.is_file():
            return place
    return None


def build_installer(version: str, icon: Path) -> dict[str, object]:
    """packaging\\orcus.iss -> dist\\OrcusAPK-Setup-<version>.exe. The script gets a UTF-8 BOM in the work folder:
    its Korean messages must not be read in the ANSI code page."""
    iscc = find_iscc()
    if iscc is None:
        return {"ok": False, "error": "ISCC.exe (Inno Setup 6) not found; set ORCUS_ISCC"}
    script = WORK / "orcus.iss"
    script.write_text((devenv.REPO / "packaging" / "orcus.iss").read_text(encoding="utf-8"), encoding="utf-8-sig")
    nums = ".".join(str(n) for n in numeric(version))
    code = devenv.run([iscc, "/Q", f"/DAppVersion={version}", f"/DNumericVersion={nums}", f"/DSourceDir={APP}",
                       f"/DIconFile={icon}", f"/O{DIST}", script], cwd=WORK)   # an argument list: no /D rewriting
    setup = DIST / f"OrcusAPK-Setup-{version}.exe"
    if code != 0 or not setup.is_file():
        return {"ok": False, "error": f"ISCC exit {code}"}
    return {"ok": True, "file": str(setup), "mb": round(setup.stat().st_size / 1e6, 1), "iscc": str(iscc)}


def publish(installer: dict[str, object]) -> dict[str, object]:
    """Copy the installer into release/ and drop the older ones there: the repository keeps one installer."""
    if installer.get("ok") is not True:
        return installer
    built = Path(str(installer["file"]))
    RELEASE.mkdir(exist_ok=True)
    for old in RELEASE.glob("OrcusAPK-Setup-*.exe"):
        if old.name != built.name:
            old.unlink()
    shutil.copy2(built, RELEASE / built.name)
    return installer | {"release": str(RELEASE / built.name)}


def main() -> int:
    py = devenv.require_venv()
    devenv.ensure_dirs()
    version = app_version()
    if "--installer-only" in sys.argv:   # the installer again from the last app folder (editing orcus.iss)
        result = build_installer(version, SRC_COPY / "src" / "orcus" / "resources" / "icon.ico")
        if "--release" in sys.argv:
            result = publish(result)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0 if result.get("ok") is True else 1
    src = copy_sources()
    WORK.mkdir(parents=True, exist_ok=True)
    spec = WORK / "orcus.spec"
    icon = src / "orcus" / "resources" / "icon.ico"
    spec.write_text(SPEC.format(src=str(src).replace("\\", "/"), lock=str(SRC_COPY / "requirements.lock"),
                                manifest=str(src / "orcus" / "emugrpc" / "generated" / "MANIFEST.json"),
                                dists=RUNTIME_DISTS, drop=set(DROP), icon=str(icon).replace("\\", "/"),
                                gui_version=str(version_file("OrcusAPK", "Orcus APK Emulator", version)),
                                cli_version=str(version_file("orcus-cli", "Orcus APK Emulator (command line)",
                                                             version))),
                    encoding="utf-8")
    started = time.monotonic()
    code = devenv.run([py, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
                       "--distpath", DIST, "--workpath", WORK / "work", spec], cwd=WORK)
    if code != 0:
        return code
    licenses = add_licenses()
    result: dict[str, object] = {"version": version, "build_s": round(time.monotonic() - started, 1),
                                 "app_mb": folder_mb(APP), "licenses": licenses}

    cli = subprocess.run([str(APP / "orcus-cli.exe"), "selftest"], capture_output=True, text=True,
                         encoding="utf-8", errors="replace", timeout=120)
    result["cli_selftest_exit"] = cli.returncode
    result["cli_selftest"] = cli.stdout.strip().splitlines()

    t = time.time() - 1
    gui = subprocess.run([str(APP / "OrcusAPK.exe"), "--selftest"], timeout=120)
    report = newest("selftest-*.txt", t)
    result["gui_selftest_exit"] = gui.returncode
    result["gui_selftest"] = report.read_text(encoding="utf-8").splitlines() if report else "no report written"

    if "--boot-check" in sys.argv:
        t = time.time() - 1
        boot = subprocess.run([str(APP / "OrcusAPK.exe"), "--boot-check"], timeout=900)
        report = newest("bootcheck-*.json", t)
        result["gui_boot_check_exit"] = boot.returncode
        if report:
            result["gui_boot_check"] = [{k: r[k] for k in ("gpu", "ok", "hypervisor", "t_discovery_s", "t_status_s",
                                                           "stop_s", "leftovers", "error")}
                                        for r in json.loads(report.read_text(encoding="utf-8"))]
    window: dict[str, object] = {"ok": True}
    if "--gui-check" in sys.argv:
        window = result["gui_window"] = gui_check()
    installer: dict[str, object] = {"ok": True}
    if "--installer" in sys.argv or "--release" in sys.argv:
        installer = build_installer(version, icon)
        if "--release" in sys.argv:
            installer = publish(installer)
        result["installer"] = installer
    print(json.dumps(result, ensure_ascii=False, indent=2))
    ok = (result["cli_selftest_exit"] == 0 and result["gui_selftest_exit"] == 0
          and result.get("gui_boot_check_exit", 0) == 0 and window.get("ok") is True and installer.get("ok") is True)
    return 0 if ok else 1


def sdk_processes() -> list[str]:
    """By image path, as A5: Google Drive for desktop runs its own crashpad_handler.exe."""
    return sorted({Path(image).name for _pid, image in winjob.processes_under(ORCUS_ROOT / "sdk")})


def gui_check() -> dict[str, object]:
    """The packaged window for real: start OrcusAPK.exe, wait for READY through the read-only `engine status`,
    then kill it the way a crash would and check that its Job took every SDK process along (§1.2)."""
    if sdk_processes():
        return {"ok": False, "error": f"SDK processes already running: {sdk_processes()}"}
    started = time.monotonic()
    gui = subprocess.Popen([str(APP / "OrcusAPK.exe")])
    ready_s = None
    status = ""
    while time.monotonic() - started < 600:
        status = subprocess.run([str(APP / "orcus-cli.exe"), "engine", "status"], capture_output=True, text=True,
                                encoding="utf-8", errors="replace", timeout=60).stdout
        if "준비됨" in status:
            ready_s = round(time.monotonic() - started, 1)
            break
        if gui.poll() is not None:
            break
        time.sleep(2)
    running = sdk_processes()
    gui.kill()
    gui.wait(10)
    time.sleep(5)
    left = sdk_processes()
    return {"ok": ready_s is not None and not left, "ready_s": ready_s, "status": status.strip().splitlines()[-1:],
            "sdk_while_running": running, "sdk_after_kill": left}


if __name__ == "__main__":
    sys.exit(main())
