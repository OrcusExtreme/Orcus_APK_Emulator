"""Packaging smoke (plan.md Phase 2 deliverable 10, acceptance A8).

1. Copy the sources out of the Drive folder (Drive briefly locks freshly written files).
2. PyInstaller onedir with two executables sharing one folder: OrcusAPK.exe (windowed) and orcus-cli.exe.
3. Run the packaged checks: orcus-cli.exe selftest, OrcusAPK.exe --selftest, and with --boot-check also
   OrcusAPK.exe --boot-check (host and host_hidden cold boots).

4. With --gui-check: start the packaged window, wait for READY, kill it, and check no SDK process is left.

Usage: py tools/dev.py build [--boot-check] [--gui-check]
"""

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.dont_write_bytecode = True
import devenv  # noqa: E402

sys.path.insert(0, str(devenv.REPO / "src"))
from orcus.common import winjob  # noqa: E402

ORCUS_ROOT = Path(r"D:\OrcusAPK")
SRC_COPY = devenv.DEV_ROOT / "src-copy"
WORK = devenv.DEV_ROOT / "build"
DIST = devenv.DEV_ROOT / "dist"
APP = DIST / "OrcusAPK"
RUNTIME_DISTS = ("PySide6_Essentials", "shiboken6", "grpcio", "protobuf", "apkInspector", "typing_extensions")

SPEC = """# Generated by tools/build.py
from PyInstaller.utils.hooks import copy_metadata

src = {src!r}
datas = [({lock!r}, "."), ({notice!r}, "."), ({manifest!r}, "orcus/emugrpc/generated")]
for dist in {dists!r}:
    datas += copy_metadata(dist)
excludes = ["tkinter", "PySide6.QtQml", "PySide6.QtQuick", "PySide6.QtOpenGL"]
# --selftest imports these by name (the GUI imports them for real too; QtNetwork = single-instance hand-over)
hiddenimports = ["PySide6.QtCore", "PySide6.QtGui", "PySide6.QtWidgets", "PySide6.QtNetwork", "apkInspector",
                 "orcus.gui.app"]


def analysis(script):
    return Analysis([script], pathex=[src], datas=datas, hiddenimports=hiddenimports, excludes=excludes,
                    noarchive=False)


gui = analysis(src + "/orcus/__main__.py")
cli = analysis(src + "/orcus/cli.py")
gui_exe = EXE(PYZ(gui.pure), gui.scripts, [], exclude_binaries=True, name="OrcusAPK", console=False,
              upx=False)
cli_exe = EXE(PYZ(cli.pure), cli.scripts, [], exclude_binaries=True, name="orcus-cli", console=True, upx=False)
COLLECT(gui_exe, gui.binaries, gui.datas, cli_exe, cli.binaries, cli.datas, name="OrcusAPK", upx=False)
"""


def copy_sources() -> Path:
    devenv.remove_tree(SRC_COPY)
    shutil.copytree(devenv.REPO / "src", SRC_COPY / "src", ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    for name in ("requirements.lock", "NOTICE", "pyproject.toml"):
        shutil.copy2(devenv.REPO / name, SRC_COPY / name)
    return SRC_COPY / "src"


def folder_mb(path: Path) -> float:
    return round(sum(f.stat().st_size for f in path.rglob("*") if f.is_file()) / 1e6, 1)


def newest(pattern: str, since: float) -> Path | None:
    logs = ORCUS_ROOT / "logs"
    files = [p for p in logs.glob(pattern) if p.stat().st_mtime >= since]
    return max(files, key=lambda p: p.stat().st_mtime) if files else None


def main() -> int:
    py = devenv.require_venv()
    devenv.ensure_dirs()
    src = copy_sources()
    WORK.mkdir(parents=True, exist_ok=True)
    spec = WORK / "orcus.spec"
    spec.write_text(SPEC.format(src=str(src).replace("\\", "/"), lock=str(SRC_COPY / "requirements.lock"),
                                notice=str(SRC_COPY / "NOTICE"),
                                manifest=str(src / "orcus" / "emugrpc" / "generated" / "MANIFEST.json"),
                                dists=RUNTIME_DISTS), encoding="utf-8")
    started = time.monotonic()
    code = devenv.run([py, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
                       "--distpath", DIST, "--workpath", WORK / "work", spec], cwd=WORK)
    if code != 0:
        return code
    result: dict[str, object] = {"build_s": round(time.monotonic() - started, 1), "app_mb": folder_mb(APP)}

    cli = subprocess.run([str(APP / "orcus-cli.exe"), "selftest"], capture_output=True, text=True,
                         encoding="utf-8", errors="replace", timeout=120)
    result["cli_selftest_exit"] = cli.returncode
    result["cli_selftest"] = cli.stdout.strip().splitlines()

    t = time.time() - 1
    gui = subprocess.run([str(APP / "OrcusAPK.exe"), "--selftest"], timeout=120)
    report = newest("selftest-*.txt", t)
    result["gui_selftest_exit"] = gui.returncode
    result["gui_selftest"] = report.read_text(encoding="utf-8").splitlines() if report else "no report written"

    if "--boot-check" in sys.argv:
        t = time.time() - 1
        boot = subprocess.run([str(APP / "OrcusAPK.exe"), "--boot-check"], timeout=900)
        report = newest("bootcheck-*.json", t)
        result["gui_boot_check_exit"] = boot.returncode
        if report:
            result["gui_boot_check"] = [{k: r[k] for k in ("gpu", "ok", "hypervisor", "t_discovery_s", "t_status_s",
                                                           "stop_s", "leftovers", "error")}
                                        for r in json.loads(report.read_text(encoding="utf-8"))]
    window: dict[str, object] = {"ok": True}
    if "--gui-check" in sys.argv:
        window = result["gui_window"] = gui_check()
    print(json.dumps(result, ensure_ascii=False, indent=2))
    ok = (result["cli_selftest_exit"] == 0 and result["gui_selftest_exit"] == 0
          and result.get("gui_boot_check_exit", 0) == 0 and window.get("ok") is True)
    return 0 if ok else 1


def sdk_processes() -> list[str]:
    """By image path, as A5: Google Drive for desktop runs its own crashpad_handler.exe."""
    return sorted({Path(image).name for _pid, image in winjob.processes_under(ORCUS_ROOT / "sdk")})


def gui_check() -> dict[str, object]:
    """The packaged window for real: start OrcusAPK.exe, wait for READY through the read-only `engine status`,
    then kill it the way a crash would and check that its Job took every SDK process along (§1.2)."""
    if sdk_processes():
        return {"ok": False, "error": f"SDK processes already running: {sdk_processes()}"}
    started = time.monotonic()
    gui = subprocess.Popen([str(APP / "OrcusAPK.exe")])
    ready_s = None
    status = ""
    while time.monotonic() - started < 600:
        status = subprocess.run([str(APP / "orcus-cli.exe"), "engine", "status"], capture_output=True, text=True,
                                encoding="utf-8", errors="replace", timeout=60).stdout
        if "준비됨" in status:
            ready_s = round(time.monotonic() - started, 1)
            break
        if gui.poll() is not None:
            break
        time.sleep(2)
    running = sdk_processes()
    gui.kill()
    gui.wait(10)
    time.sleep(5)
    left = sdk_processes()
    return {"ok": ready_s is not None and not left, "ready_s": ready_s, "status": status.strip().splitlines()[-1:],
            "sdk_while_running": running, "sdk_after_kill": left}


if __name__ == "__main__":
    sys.exit(main())
