@pytest.mark.parametrize("name", list(ALL))
def test_bky_events_name_real_components(name: str) -> None:
    for s in ALL[name].screens:
        root = ET.fromstring(aia.bky(s))
        versions = root.find(f"{NS}yacodeblocks")
        assert versions is not None and versions.attrib == {"ya-version": "239", "language-version": "40"}
        instances = {m.attrib["instance_name"] for m in root.iter("{http://www.w3.org/1999/xhtml}mutation")}
        assert instances <= names(s).keys()
        ids = [blk.attrib["id"] for blk in root.iter(f"{NS}block")]
        assert len(ids) == len(set(ids))


