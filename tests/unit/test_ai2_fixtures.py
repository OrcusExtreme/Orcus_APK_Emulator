NS = "{https://developers.google.com/blockly/xml}"


def names(s: aia.Screen) -> dict[str, aia.Component]:
    return {c.name: c for c in s.form().walk()}


@pytest.mark.parametrize("name", list(ALL))
def test_static_checks_pass(name: str) -> None:
    assert aia.problems(ALL[name]) == []


@pytest.mark.parametrize("name", list(ALL))
def test_aia_has_no_yail_and_build_zip_has_it(name: str, tmp_path) -> None:
    p = ALL[name]
    with zipfile.ZipFile(p.write_zip(tmp_path / "a.aia", with_yail=False)) as z:
        aia_names = set(z.namelist())
    with zipfile.ZipFile(p.write_zip(tmp_path / "b.zip", with_yail=True)) as z:
        build_names = set(z.namelist())
    src = p.src_dir()
    assert "youngandroidproject/project.properties" in aia_names
    for s in p.screens:
        assert {f"{src}/{s.name}.scm", f"{src}/{s.name}.bky"} <= aia_names
        assert f"{src}/{s.name}.yail" not in aia_names
    assert build_names - aia_names == {f"{src}/{s.name}.yail" for s in p.screens}
    assert {f"assets/{a}" for a in p.assets} <= aia_names


