def test_probe_label_words_are_not_button_prefixes() -> None:
    """Device tests find a label by its first word; a button starting with that word would be ambiguous."""
    comps = [c for s in ALL["OrcusProbe"].screens for c in s.form().walk()]
    words = {c.props["Text"].split(" ")[0] for c in comps if c.type == "Label"}
    buttons = [c.props["Text"] for c in comps if c.type == "Button"]
    assert not [t for t in buttons if t.split(" ")[0] in words]


